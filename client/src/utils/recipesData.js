  const data = lang === 'ta' ? RECIPE_DATA_TA[type] : RECIPE_DATA_EN[type];

  // Base per person ratios
  const riceGrams = people * 125;
  const waterMl = people * 187.5; // 1:1.5 ratio
  const mainQty = data.isEgg ? people : people * 125;
  const onionGrams = people * 50;
  const tomatoGrams = people * 37.5;
  const gingerGarlicGrams = people * 12.5;
  const oilMl = people * 15;
  const gheeMl = people * 10;
